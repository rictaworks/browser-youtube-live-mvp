// Package core は、中継（Go）の Domain Core の置き場です（requirements.md 2.5・15 章）。
//
// 入出力（WebSocket・RTMPS・HTTP）に依存しない、純粋な Go です。時刻・設定値・現況は引数で受け取ります
// （実時計を読みません。同じ入力に、同じ出力を返します）。符号化データの中身に触れません（再エンコードしません。
// 11.1・11.10）。WebSocket のハンドラと RTMPS のクライアントは、この外（アダプタ）です。
//
// パッケージ:
//
//	contract  3 層の契約の定数（#3）
//	frame     WebSocket のバイナリフレームの符号化・復号・検証（11.9）と、時刻の整合（TimeGuard）
//	rebase    時刻の再基準化（RTMPS の接続ごとに 0 起点。復帰時は欠落を詰める。11.10）
//	policer   受信ビットレートの監視（直近 10 秒の平均が、プロファイルの映像ビットレートの上限の 1.5 倍を超えたら真）
//	probe     回線計測（最初の計測データから 3 秒間の受領量で、実効スループットを求める。11.8）
//	watchdog  メディアの無通信の検出（映像または音声が 5 秒届かなければ真）
//	buffer    送出待ちバッファの方針（1.5 秒分で抑制指示、3 秒分で送出失敗）
//	liveness  心拍の応答の喪失の判定（60 秒得られなければ、送出を止める）
//
// 状態を持つ型（TimeGuard・TimestampRebaser・IngressPolicer・ProbeMeter・MediaWatchdog・Policy・HeartbeatLiveness）は、
// ゴルーチンから並行に呼びません。取り込みセッションが、呼び出しを直列にします（時刻は、その排他の内側で取得して渡します）。
// 独立したインスタンスは、互いに影響しません（グローバルな状態を持ちません）。
//
// このディレクトリの下のすべてのソースが、入出力・実時計・乱数・標準出力に依存しないこと、グローバル変数を持たないこと、
// 日本語の文言を直書きしないことは、rules_test.go が走査して確かめます。
