import { formatJst } from "./format-jst";

describe("formatJst", () => {
  it.each([
    ["UTC 12:30 は、JST の同じ日の 21:30", "2026-10-06T12:30:00Z", "2026-10-06 21:30"],
    ["UTC 15:00 は、JST の翌日 00:00（日付をまたぐ）", "2026-10-06T15:00:00Z", "2026-10-07 00:00"],
    ["利用日の区切り（JST 03:00）", "2026-10-05T18:00:00Z", "2026-10-06 03:00"],
    ["利用日の区切りの 1 分前（JST 02:59）", "2026-10-05T17:59:00Z", "2026-10-06 02:59"],
    ["年をまたぐ", "2026-12-31T15:00:00Z", "2027-01-01 00:00"],
    ["月をまたぐ", "2026-09-30T20:00:00Z", "2026-10-01 05:00"],
    ["うるう日", "2028-02-28T15:00:00Z", "2028-02-29 00:00"],
    ["1 桁の月・日・時・分は 0 で埋める", "2026-01-02T00:05:00Z", "2026-01-02 09:05"],
    ["秒は切り捨てる", "2026-10-06T12:30:59Z", "2026-10-06 21:30"],
    ["ミリ秒も切り捨てる", "2026-10-06T12:30:00.999Z", "2026-10-06 21:30"],
  ])("%s", (_label, iso, expected) => {
    expect(formatJst(new Date(iso))).toBe(expected);
  });

  it("オフセット付きの時刻も、同じ瞬間なら同じ表示になる", () => {
    expect(formatJst(new Date("2026-10-06T21:30:00+09:00"))).toBe("2026-10-06 21:30");
    expect(formatJst(new Date("2026-10-06T00:00:00-05:00"))).toBe("2026-10-06 14:00");
  });

  it("無効な Date は、例外にする（NaN を含む文字列を返さない）", () => {
    expect(() => formatJst(new Date("not a date"))).toThrow(RangeError);
  });
});
